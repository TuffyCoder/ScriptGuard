/** Cache of the firewall settings so request handling stays synchronous. */
let fwCache = Object.assign({}, DEFAULTS.firewall);
let modeCache = 'BASIC';

/** Is the network firewall enforcing for this mode right now?
 *  Ads are blocked in EVERY active mode (BASIC, PRO, MAXIMUM) - only
 *  OFF and an explicit "do not block" setting silence the firewall.
 *  'always' is accepted as a legacy alias of 'armed'. */
function firewallActive() {
  if (modeCache === 'OFF') return false;
  if (fwCache.adBlockMode === 'off') return false;
  return fwCache.adBlockMode === 'armed' || fwCache.adBlockMode === 'always';
}

function hostOfUrl(url) {
  try { return new URL(url).hostname.toLowerCase() || ''; }
  catch (e) { return ''; }
}

/** Registrable-domain guess (last two labels) - same rule content.js uses. */
function baseDomainOf(host) {
  const parts = (host || '').split('.').filter(Boolean);
  if (parts.length <= 2) return parts.join('.');
  return parts.slice(-2).join('.');
}

/** Does host sit on (or under) any known ad/tracker domain? */
function isAdHost(host) {
  if (!host) return false;
  for (const ad of AD_HOSTS) {
    if (!ad || ad.indexOf('.') === -1) continue; // skip guard entries
    if (host === ad || host.endsWith('.' + ad)) return true;
  }
  return false;
}

/** Remove tracking params from an http(s) URL. Returns null if clean. */
function stripTrackingParams(url) {
  try {
    const u = new URL(url);
    if (u.protocol !== 'http:' && u.protocol !== 'https:') return null;
    let changed = false;
    for (const name of Array.from(u.searchParams.keys())) {
      const lower = name.toLowerCase();
      const hit = TRACK_PARAMS.some((p) => {
        if (p.endsWith('_')) return lower.indexOf(p) === 0; // prefix family
        return lower === p;
      });
      if (hit) { u.searchParams.delete(name); changed = true; }
    }
    // reddit/twitter style fragment crumbs
    if (/(^|\/)#.*(utm_|fbclid|gclid)/i.test(u.href)) { /* rare - ignore */ }
    return changed ? u.href : null;
  } catch (e) {
    return null;
  }
}

