/**
 * ScriptGuard - background (event) page.
 *
 * The background page runs the NETWORK firewall. Script deletion itself
 * still happens in content.js, directly in the DOM.
 *
 * Responsibilities:
 *   1. Seed default settings on first install.
 *   2. Maintain a per-tab badge showing how many scripts were deleted.
 *   3. Reflect the active mode in the toolbar: icon colour
 *      (OFF=gray, BASIC=green, PRO=yellow, MAXIMUM=red), tooltip.
 *   4. Ad & tracker firewall: webRequest-level blocking of requests to
 *      known ad / tracker hosts (armed in PRO + MAXIMUM, or everywhere).
 *   5. Privacy headers: Sec-GPC + DNT on every request.
 *   6. Tracking-parameter stripping (utm_*, fbclid, gclid, ...) on nav.
 *   7. Optional auto-wipe: clear a site's data when its tab closes.
 *   8. Export / import the rule database (JSON) for backup and sharing.
 *
 * Everything here uses the promise-based `browser.*` namespace (Firefox).
 */

'use strict';

/* ---------------------------------------------------------------------
 * Default settings
 *
 * The shape of storage.local:
 *   {
 *     mode: "OFF" | "BASIC" | "PRO" | "MAXIMUM",
 *     rules:     { "<site>": ["<pattern>", ...], ... },
 *     whitelist: { "<site>": ["<pattern>", ...], ... },
 *     globalWhitelist: ["<pattern>", ...],
 *     regexRules:      ["<RegExp source>", ...],
 *     heuristics: { "<site>": ["<pattern>", ...], ... },
 *     shields:   { webrtc: true, blob: true },
 *     firewall:  { adBlockMode: "off"|"armed"|"always",
 *                  stripTracking: true, gpc: true, autoWipe: false },
 *     labels:    { "<site>": { "<pattern>": "<human label>" }, ... },
 *     trustedSites: ["<host>", ...],
 *     stats:     { "<site>": <deleted count> },
 *     netStats:  { "<site>": <requests blocked by the firewall> }
 *   }
 *
 * A pattern is either a normalized script URL, an "inline:<hash>" marker
 * for inline scripts, or a URL prefix ending in "*" (wildcard).
 *
 * BASIC is the factory default on purpose: a fresh install must never
 * silently break the web. Users opt into PRO / MAXIMUM themselves.
 * ------------------------------------------------------------------- */

const DEFAULTS = {
  mode: 'BASIC',
  rules: {},
  whitelist: {},
  globalWhitelist: [],
  regexRules: [],
  heuristics: {},
  shields: { webrtc: true, blob: true },
  firewall: {
    adBlockMode: 'armed',  // 'off' | 'armed' (BASIC + PRO + MAXIMUM; 'always' kept as legacy alias)
    stripTracking: true,   // remove utm_*/fbclid/gclid/... from URLs
    gpc: true,             // Sec-GPC + DNT headers
    autoWipe: false        // wipe site data when its tab closes
  },
  labels: {},
  trustedSites: [],
  stats: {},
  netStats: {}             // site -> requests blocked by the firewall
};

