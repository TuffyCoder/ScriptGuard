/* ---------------------------------------------------------------------
 * 3b. Network firewall (ads, trackers, pings, GPC headers)
 *
 * Uses blocking webRequest (Firefox MV2) to cancel requests to known
 * ad / tracker infrastructure BEFORE anything is downloaded. This is
 * what actually removes ads: ad iframes, ad images, ad XHR and the
 * beacons that report your browsing.
 *
 *   - Host block: any request to a known ad/tracker domain.
 *   - Path block: generic ad paths, but ONLY on third-party requests.
 *   - Ping block: <a ping=...> hyperlink auditing is pure tracking.
 *   - Headers:    Sec-GPC + DNT appended to every outgoing request.
 *
 * Blocked counts are kept per tab (for the popup) and flushed to
 * storage.netStats every few seconds (all-time, per site).
 * ------------------------------------------------------------------- */

const netBlocked = new Map();  // tabId -> blocked count this page load
const netDelta = new Map();    // site key -> unflushed all-time delta
let netFlushTimer = null;

function bumpNetBlocked(tabId, siteKey) {
  if (tabId >= 0) netBlocked.set(tabId, (netBlocked.get(tabId) || 0) + 1);
  if (siteKey) netDelta.set(siteKey, (netDelta.get(siteKey) || 0) + 1);
  if (!netFlushTimer) netFlushTimer = setTimeout(flushNetStats, 3000);
}

async function flushNetStats() {
  netFlushTimer = null;
  if (netDelta.size === 0) return;
  const pending = Array.from(netDelta.entries());
  netDelta.clear();
  try {
    const snapshot = await browser.storage.local.get('netStats');
    const stats = snapshot.netStats || {};
    for (const [site, n] of pending) {
      stats[site] = (stats[site] || 0) + n;
    }
    await browser.storage.local.set({ netStats: stats });
  } catch (e) { /* stats are cosmetic - never fatal */ }
}

/** Third-party? The request target must not share the page's base domain. */
function isThirdPartyRequest(details) {
  const target = baseDomainOf(hostOfUrl(details.url));
  const origin = baseDomainOf(hostOfUrl(details.initiator || details.originUrl || ''));
  if (!origin || !target) return true; // no initiator = browser-level = treat strict
  return origin !== target;
}

browser.webRequest.onBeforeRequest.addListener((details) => {
  if (!firewallActive()) return;

  // Hyperlink auditing (<a ping>) is tracking, full stop.
  if (details.type === 'ping') {
    bumpNetBlocked(details.tabId, baseDomainOf(hostOfUrl(details.url)));
    return { cancel: true };
  }

  const host = hostOfUrl(details.url);
  if (isAdHost(host)) {
    bumpNetBlocked(details.tabId, baseDomainOf(host));
    return { cancel: true };
  }

  // Generic ad paths - only trusted on cross-site requests so a
  // first-party URL like /admin or /download can never false-positive.
  if (isThirdPartyRequest(details)) {
    const path = (() => {
      try { return new URL(details.url).pathname; } catch (e) { return ''; }
    })();
    for (const re of AD_PATH_PATTERNS) {
      if (re.test(path)) {
        bumpNetBlocked(details.tabId, baseDomainOf(host));
        return { cancel: true };
      }
    }
  }
}, { urls: ['<all_urls>'] }, ['blocking']);

/** Append Global Privacy Control + DNT to every outgoing request. */
browser.webRequest.onBeforeSendHeaders.addListener((details) => {
  if (!fwCache.gpc || modeCache === 'OFF') return;
  const headers = details.requestHeaders || [];
  const set = (name, value) => {
    for (const h of headers) {
      if (h.name.toLowerCase() === name.toLowerCase()) { h.value = value; return; }
    }
    headers.push({ name: name, value: value });
  };
  set('Sec-GPC', '1');
  set('DNT', '1');
  return { requestHeaders: headers };
}, { urls: ['<all_urls>'] }, ['blocking', 'requestHeaders']);

/** Wipe everything a site stored, called when its tab closes (opt-in). */
async function wipeSiteData(host) {
  try {
    const origin = 'https://' + host;
    await browser.browsingData.remove(
      { origins: [origin] },
      {
        cookies: true,
        localStorage: true,
        indexedDB: true,
        serviceWorkers: true,
        cacheStorage: true
      }
    );
    // http variant too, in case the site was served over plain http
    await browser.browsingData.remove(
      { origins: ['http://' + host] },
      { cookies: true, localStorage: true, indexedDB: true, serviceWorkers: true, cacheStorage: true }
    );
  } catch (e) { /* best effort - some data types may not exist */ }
}

/* ---------------------------------------------------------------------
 * 4. Export / import
 *
 * Export writes the whole settings object as pretty-printed JSON and
 * opens it in a new tab (blob URL), so the user can save it from there.
 * Import merges a JSON object into the existing database: per-domain
 * rule lists are unioned, never overwritten, so importing a friend's
 * rules cannot silently delete your own. Global whitelist and regex
 * lists are unioned as arrays; shields are merged key by key.
 * ------------------------------------------------------------------- */

async function exportRules() {
  try {
    const snapshot = await browser.storage.local.get(ALL_KEYS);
    const json = JSON.stringify(snapshot, null, 2);
    const blob = new Blob([json], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    await browser.tabs.create({ url: url });
    // Give the tab time to load before the blob is invalidated.
    setTimeout(() => URL.revokeObjectURL(url), 5 * 60 * 1000);
  } catch (err) {
    console.error('[ScriptGuard] export failed:', err);
  }
}

async function importRules(incoming) {
  try {
    const patch = {};

    if (incoming && typeof incoming.mode === 'string' && VALID_MODES.indexOf(incoming.mode) !== -1) {
      patch.mode = incoming.mode;
    }

    for (const key of ['rules', 'whitelist', 'labels', 'stats', 'heuristics']) {
      if (incoming && incoming[key] && typeof incoming[key] === 'object' && !Array.isArray(incoming[key])) {
        const current = await browser.storage.local.get(key);
        patch[key] = deepMergeMaps(current[key] || {}, incoming[key]);
      }
    }

    for (const key of ['globalWhitelist', 'regexRules']) {
      if (incoming && Array.isArray(incoming[key])) {
        const current = await browser.storage.local.get(key);
        patch[key] = union(current[key] || [], incoming[key].filter((h) => typeof h === 'string'));
      }
    }

    if (incoming && Array.isArray(incoming.trustedSites)) {
      const current = await browser.storage.local.get('trustedSites');
      patch.trustedSites = union(
        current.trustedSites || [],
        incoming.trustedSites.filter((h) => typeof h === 'string')
      );
    }

    if (incoming && incoming.shields && typeof incoming.shields === 'object' && !Array.isArray(incoming.shields)) {
      const current = await browser.storage.local.get('shields');
      const merged = Object.assign({ webrtc: true, blob: true }, current.shields || {});
      if (typeof incoming.shields.webrtc === 'boolean') merged.webrtc = incoming.shields.webrtc;
      if (typeof incoming.shields.blob === 'boolean') merged.blob = incoming.shields.blob;
      patch.shields = merged;
    }

    if (incoming && incoming.firewall && typeof incoming.firewall === 'object' && !Array.isArray(incoming.firewall)) {
      const current = await browser.storage.local.get('firewall');
      const merged = Object.assign({}, DEFAULTS.firewall, current.firewall || {});
      if (['off', 'armed', 'always'].indexOf(incoming.firewall.adBlockMode) !== -1) {
        merged.adBlockMode = incoming.firewall.adBlockMode;
      }
      if (typeof incoming.firewall.stripTracking === 'boolean') merged.stripTracking = incoming.firewall.stripTracking;
      if (typeof incoming.firewall.gpc === 'boolean') merged.gpc = incoming.firewall.gpc;
      if (typeof incoming.firewall.autoWipe === 'boolean') merged.autoWipe = incoming.firewall.autoWipe;
      patch.firewall = merged;
    }

    if (incoming && incoming.netStats && typeof incoming.netStats === 'object' && !Array.isArray(incoming.netStats)) {
      // All-time firewall counts: take the MAX of the two, never subtract.
      const current = await browser.storage.local.get('netStats');
      const merged = Object.assign({}, current.netStats || {});
      for (const site of Object.keys(incoming.netStats)) {
        const v = incoming.netStats[site] | 0;
        if (v > (merged[site] || 0)) merged[site] = v;
      }
      patch.netStats = merged;
    }

    if (Object.keys(patch).length > 0) {
      await browser.storage.local.set(patch);
    }
  } catch (err) {
    console.error('[ScriptGuard] import failed:', err);
  }
}

/** Merge two "domain -> array of strings" maps, unioning the arrays. */
function deepMergeMaps(target, source) {
  const out = Object.assign({}, target);
  for (const domain of Object.keys(source || {})) {
    const incomingList = Array.isArray(source[domain]) ? source[domain] : [];
    const existingList = Array.isArray(out[domain]) ? out[domain] : [];
    out[domain] = union(existingList, incomingList);
  }
  return out;
}

/** Union of two arrays of strings, order-preserving, no duplicates. */
function union(a, b) {
  const seen = new Set(a);
  const out = a.slice();
  for (const item of b) {
    if (!seen.has(item)) {
      seen.add(item);
      out.push(item);
    }
  }
  return out;
}
